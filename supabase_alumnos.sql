create table if not exists public.alumnos (
    id          bigint generated by default as identity primary key,
    nombres     text not null,
    apellidos   text,
    paralelo    text not null,
    correo      text,
    telefono    text,
    foto        text,
    created_at  timestamptz not null default now()
);

-- Seguridad a nivel de fila (RLS).
-- Con la clave publishable, la app solo puede leer lo que permitan las políticas.
alter table public.alumnos enable row level security;

drop policy if exists "Lectura publica de alumnos" on public.alumnos;
create policy "Lectura publica de alumnos"
    on public.alumnos
    for select
    to anon, authenticated
    using (true);

